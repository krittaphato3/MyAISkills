#!/usr/bin/env python3
"""Generate docs/catalog-report.md from the catalog on disk.

Every number in the report is computed here; nothing is hand-maintained prose.
Run after any change to skills/, agents/, commands/.

Usage:
    python tools/gen_catalog_report.py
    python tools/gen_catalog_report.py --check   # exit 1 if the file is stale
"""
from __future__ import annotations

import argparse
import io
import re
import sys
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / "skills"
AGENTS = ROOT / "agents"
COMMANDS = ROOT / "commands"
OUT = ROOT / "docs" / "catalog-report.md"
ROUTING = ROOT / "docs" / "ROUTING.md"

# The deployed copy the harness actually loads. May not exist on every machine.
DEPLOYED = Path.home() / ".config" / "opencode"

DOMAINS = ["doctrine", "architecture", "delivery", "production", "security",
           "languages", "roblox", "meta", "fundamentals"]
GRADE_SECTIONS = {
    "G2": ["## WHEN TO USE", "## WHEN NOT TO USE", "## DECISION TREE",
           "## FAILURE MODES & MITIGATIONS", "## VERIFICATION GATE", "## REFERENCES"],
    "G3": ["## WHEN TO USE", "## WHEN NOT TO USE", "## DECISION TREE",
           "## FAILURE MODES & MITIGATIONS", "## QUANTITATIVE RULES",
           "## VERIFICATION GATE", "## REFERENCES"],
}
STALE_DAYS = 90


def read(path: Path) -> str:
    return io.open(path, encoding="utf-8", errors="replace").read().replace("\r\n", "\n")


def frontmatter(path: Path) -> tuple[dict, str]:
    raw = read(path)
    if not raw.startswith("---\n"):
        return {}, raw
    parts = raw.split("---", 2)
    if len(parts) < 3:
        return {}, raw
    try:
        meta = yaml.safe_load(parts[1]) or {}
    except yaml.YAMLError:
        # Command files may carry non-YAML hints (e.g. `argument-hint: [path]`).
        # Fall back to one-line key: value parsing so a report never dies on one file.
        meta = {}
        for line in parts[1].splitlines():
            if ":" in line and not line.startswith((" ", "\t", "#")):
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip().strip("'\"")
    return (meta if isinstance(meta, dict) else {}), parts[2]


def load_skills() -> dict[str, dict]:
    out: dict[str, dict] = {}
    for path in sorted(SKILLS.glob("*/SKILL.md")):
        meta, body = frontmatter(path)
        md = meta.get("metadata") or {}
        out[path.parent.name] = {
            "meta": meta, "md": md if isinstance(md, dict) else {}, "body": body,
            "desc": (meta.get("description") or "").strip(),
            "version": str((md or {}).get("version") or "?"),
            "domain": (md or {}).get("domain") or "?",
            "grade": (md or {}).get("grade") or "?",
            "status": (md or {}).get("status") or "?",
            "owner": (md or {}).get("authored-by") or "?",
            "reviewed": str((md or {}).get("last-reviewed") or "?"),
            "lines": body.count("\n"),
        }
    return out


def load_agents() -> dict[str, dict]:
    out = {}
    for path in sorted(AGENTS.glob("*.md")):
        meta, body = frontmatter(path)
        out[path.stem] = {"meta": meta, "body": body,
                          "desc": (meta.get("description") or "").strip()}
    return out


def load_commands() -> dict[str, dict]:
    out = {}
    for path in sorted(COMMANDS.glob("*.md")):
        meta, body = frontmatter(path)
        out[path.stem] = {"meta": meta, "body": body,
                          "desc": (meta.get("description") or "").strip()}
    return out


def router_text(include_index: bool = True) -> str:
    parts = []
    for p in (ROOT / "AGENTS.md", DEPLOYED / "AGENTS.md"):
        if p.is_file():
            parts.append(read(p))
    if include_index and ROUTING.is_file():
        parts.append(read(ROUTING))
    return "\n".join(parts)


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |")
    return out


def build() -> str:
    skills, agents, commands = load_skills(), load_agents(), load_commands()
    router = router_text()
    core_router = router_text(include_index=False)
    today = date.today()
    L: list[str] = []

    L += ["<!-- Generated by tools/gen_catalog_report.py. Do not edit by hand. -->",
          "# Catalog report", "",
          f"Generated {today.isoformat()} from the files on disk.", "",
          f"- skills: **{len(skills)}**",
          f"- agents: **{len(agents)}**",
          f"- commands: **{len(commands)}**",
          f"- playbooks: **{len(list((SKILLS / 'ozone-mode' / 'playbooks').glob('*.md')))}**", ""]

    # ---- reachability ----
    core_skills = sorted(n for n in skills if n not in core_router)
    core_agents = sorted(n for n in agents if n not in core_router)
    unrouted_skills = sorted(n for n in skills if n not in router)
    unrouted_agents = sorted(n for n in agents if n not in router)
    L += ["## Reachability", "",
          "Two columns: reachable from the hand-written router tables in `AGENTS.md`, and "
          "reachable once the generated `docs/ROUTING.md` index is consulted.", "",
          f"- from `AGENTS.md` alone: {len(skills) - len(core_skills)}/{len(skills)} skills, "
          f"{len(agents) - len(core_agents)}/{len(agents)} agents",
          f"- including `docs/ROUTING.md`: {len(skills) - len(unrouted_skills)}/{len(skills)} skills, "
          f"{len(agents) - len(unrouted_agents)}/{len(agents)} agents", ""]
    if core_skills:
        L += [f"Skills not named in any `AGENTS.md` ({len(core_skills)}): "
              + ", ".join(f"`{n}`" for n in core_skills), ""]
    if core_agents:
        L += [f"Agents not named in any `AGENTS.md` ({len(core_agents)}): "
              + ", ".join(f"`{n}`" for n in core_agents), ""]

    # ---- budget ----
    skill_chars = sum(len(s["desc"]) for s in skills.values())
    agent_chars = sum(len(a["desc"]) for a in agents.values())
    L += ["## Always-loaded budget", "",
          "Descriptions sit in every session's context before any work starts.", ""]
    L += table(["Component", "Chars", "Est. tokens"], [
        ["skill descriptions", skill_chars, skill_chars // 4],
        ["agent descriptions", agent_chars, agent_chars // 4],
        ["**total**", f"**{skill_chars + agent_chars}**", f"**{(skill_chars + agent_chars) // 4}**"],
    ])
    L += ["", "Per `agent-config-maintenance`: each description is 120–1024 chars, average target "
              "250–400. The total is `skills × average`, so growth is paid for by merging or "
              "retiring an equal amount.", ""]

    # ---- domains ----
    L += ["## Domains", ""]
    by_domain: dict[str, list[str]] = defaultdict(list)
    for name, s in skills.items():
        by_domain[s["domain"]].append(name)
    rows = []
    for d in DOMAINS:
        names = by_domain.get(d, [])
        grades = Counter(skills[n]["grade"] for n in names)
        rows.append([d, len(names), grades.get("G1", 0), grades.get("G2", 0), grades.get("G3", 0)])
    rows.append(["**total**", f"**{len(skills)}**", "", "", ""])
    L += table(["Domain", "Skills", "G1", "G2", "G3"], rows) + [""]

    # ---- grades ----
    L += ["## Grade conformance", "",
          "Each grade declares required body sections. Skills missing them are listed below.", ""]
    missing: dict[str, list[str]] = defaultdict(list)
    for name, s in skills.items():
        for section in GRADE_SECTIONS.get(s["grade"], []):
            if section.lower() not in s["body"].lower():
                missing[name].append(section.replace("## ", ""))
    conforming = len(skills) - len(missing)
    L += [f"- conforming: {conforming}/{len(skills)}",
          f"- non-conforming: {len(missing)}", ""]
    if missing:
        L += table(["Skill", "Grade", "Missing sections"],
                   [[f"`{n}`", skills[n]["grade"], ", ".join(m)] for n, m in sorted(missing.items())]) + [""]

    # ---- versions / review ----
    L += ["## Hygiene", ""]
    versions = Counter(s["version"] for s in skills.values())
    L += ["Version families: " + ", ".join(f"`{v}` x{c}" for v, c in versions.most_common()) + "", ""]
    reviews = Counter(s["reviewed"] for s in skills.values())
    L += ["Review stamps: " + ", ".join(f"`{v}` x{c}" for v, c in sorted(reviews.items())) + "", ""]
    over = sorted(((s["lines"], n) for n, s in skills.items()), reverse=True)[:5]
    L += ["Largest bodies (lines): " + ", ".join(f"`{n}` {c}" for c, n in over) + "", ""]
    nonactive = [(n, s["status"]) for n, s in skills.items() if s["status"] != "active"]
    L += ["Non-active status: " + (", ".join(f"`{n}` ({s})" for n, s in nonactive) or "none") + "", ""]

    # ---- owner coverage ----
    owned = Counter(s["owner"] for s in skills.values())
    unowned = sorted(a for a in agents if owned.get(a, 0) == 0)
    L += ["## Ownership", "",
          f"Agents owning at least one skill: {sum(1 for a in agents if owned.get(a, 0))}/{len(agents)}", ""]
    L += [f"Agents owning none ({len(unowned)}): " + (", ".join(f"`{a}`" for a in unowned) or "none"), ""]

    # ---- commands ----
    L += ["## Commands", ""]
    if commands:
        documented = [n for n in commands if f"/{n}" in router]
        L += [f"- command files: {len(commands)}",
              f"- mentioned in a router doc: {len(documented)}/{len(commands)}", ""]
        L += table(["Command", "Documented", "Description"],
                   [[f"`/{n}`", "yes" if n in documented else "**no**", c["desc"][:90]]
                    for n, c in sorted(commands.items())]) + [""]
    declared = sorted(set(re.findall(r"`/([a-z][a-z0-9-]+)`", router)))
    phantom = [d for d in declared if d not in commands]
    L += [f"Commands referenced in docs but not on disk: {', '.join(f'`/{p}`' for p in phantom) or 'none'}", ""]

    # ---- routing eval ----
    cases_path = ROOT / "tools" / "routing_cases.json"
    L += ["## Routing eval coverage", ""]
    if cases_path.is_file():
        import json
        cases = json.loads(read(cases_path)).get("cases", [])
        tested = {c.get("skill") for c in cases if c.get("skill")}
        negative = sum(1 for c in cases if not c.get("skill"))
        L += [f"- cases: {len(cases)}",
              f"- distinct skills tested: {len(tested)}/{len(skills)}",
              f"- negative cases (must match nothing): {negative}",
              f"- skills never tested: {len(skills) - len(tested)}", ""]
        L += ["No runner executes this fixture; `lint_config.py` validates its schema only.", ""]
    else:
        L += ["`tools/routing_cases.json` missing.", ""]

    # ---- deployed drift ----
    L += ["## Deployed copy", ""]
    target_skills = DEPLOYED / "skills"
    if target_skills.is_dir():
        drift, missing_deployed = [], []
        for rel in ("skills", "agents", "commands"):
            src_root = ROOT / rel
            dst_root = DEPLOYED / rel
            if not dst_root.is_dir():
                continue
            for f in src_root.rglob("*"):
                if not f.is_file():
                    continue
                dst = dst_root / f.relative_to(src_root)
                if not dst.exists():
                    missing_deployed.append(str(f.relative_to(ROOT)))
                elif f.read_bytes() != dst.read_bytes():
                    drift.append(str(f.relative_to(ROOT)))
        L += [f"- source: `{ROOT}`",
              f"- deployed: `{DEPLOYED}`",
              f"- files only in source: {len(missing_deployed)}",
              f"- files that differ: {len(drift)}", ""]
        for rel in (missing_deployed + drift)[:20]:
            L.append(f"  - `{rel}`")
        L += ["", "Run `python tools/sync_catalog.py --check` for the authoritative diff.", ""]
    else:
        L += ["No deployed copy found on this machine.", ""]

    L += ["## Regenerating", "",
          "```bash",
          "python tools/gen_routing.py            # docs/ROUTING.md",
          "python tools/gen_catalog_report.py     # this file",
          "python tools/lint_config.py --write-index",
          "```", ""]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the report is stale")
    args = ap.parse_args(argv)
    content = build()
    if args.check:
        current = read(OUT) if OUT.is_file() else ""
        if current != content:
            print(f"{OUT.relative_to(ROOT)} is stale; rerun tools/gen_catalog_report.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
